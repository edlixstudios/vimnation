const vimSource = "https://neovim.io/doc/user/usr_04/";
const lazySource = "https://www.lazyvim.org/keymaps";
const T = (value: string, action?: string, alternatives?: string[]): Goal => ({
  kind: "text",
  value,
  action,
  alternatives,
});
const C = (value: number): Goal => ({ kind: "cursor", value });
const A = (...value: string[]): Goal => ({ kind: "actions", value });
function lesson(
  id: string,
  chapter: number,
  title: string,
  intro: string,
  task: string,
  initial: string,
  goal: Goal,
  keys: string[],
  tip: string,
  cursor = 0,
): Lesson {
  const lazy = chapter >= 5 && !["combine", "cleanup"].includes(id);
  return {
    id,
    chapter,
    title,
    intro,
    task,
    initial,
    cursor,
    goal,
    keys,
    tip,
    lazy,
    source: lazy ? lazySource : vimSource,
    hints: [
      intro,
      `Versuche diese Folge: ${keys.map((k) => (k === " " ? "Space" : k)).join(" → ")}`,
    ],
    solution: tip,
  };
}
