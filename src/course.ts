export function isComplete(lesson: Lesson, s: Snapshot): boolean {
  if (s.mode !== "NORMAL") return false;
  const g = lesson.goal;
  if (g.kind === "actions") return g.value.every((a) => s.actions.includes(a));
  if (g.kind === "cursor")
    return s.cursor === g.value && s.text === lesson.initial;
  return (
    [g.value, ...(g.alternatives || [])].includes(s.text) &&
    (!g.action || s.actions.includes(g.action))
  );
}
