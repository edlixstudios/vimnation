export type Snapshot = {
  text: string;
  cursor: number;
  mode: string;
  actions: string[];
  changed: boolean;
};
export type Goal =
  | { kind: "text"; value: string; alternatives?: string[]; action?: string }
  | { kind: "cursor"; value: number }
  | { kind: "actions"; value: string[] };
